func canPartition(nums []int) bool {
	sort.Ints(nums)
	sum := 0
	for _, num := range nums {
		sum += num
	}
	if sum%2 != 0 {
		return false
	}

	sum /= 2

	return findCanPartition(nums, []int{sum})
}

func findCanPartition(nums []int, targets []int) bool {
	trueNumber := 0
	for _, target := range targets {
		index := slices.Index(nums, target)
		if index >= 0 {
			// 找到了
			trueNumber++
			nums[index] = -1
		} else {
			newTargets := []int{}
			if target == 1 {
				return false
			}
			if target%2 != 0 {
				newTargets = append(newTargets, int(math.Ceil(float64(target)/2)))
			} else {
				newTargets = append(newTargets, target/2)
			}
			newTargets = append(newTargets, target/2)
			if findCanPartition(nums, newTargets) {
				trueNumber++
			}
		}
	}

	return trueNumber == len(targets)
}

